#!/usr/bin/env bash
# Print the Homebrew formula that installs a binary package.
#
#   scripts/homebrew-formula.sh <tarball> [<url>]
#
# The version, checksum and minimum macOS come from the tarball (made by
# scripts/package.sh). <url> is where the formula downloads it from, by default
# the asset of release v<version> on GitHub. The release workflow commits the
# output to the tap as Formula/qemu-gl.rb.

source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

[ $# -ge 1 ] && [ $# -le 2 ] || die "usage: scripts/homebrew-formula.sh <tarball> [<url>]"
tarball="$1"
[ -f "$tarball" ] || die "$tarball not found"

name="$(basename "$tarball" -macos-arm64.tar.xz)"
version="${name#"$PACKAGE_NAME"-}"
[ "$version" != "$name" ] || die "$tarball isn't a $PACKAGE_NAME package"
url="${2:-$PROJECT_URL/releases/download/v$version/$name-macos-arm64.tar.xz}"
sha256="$(shasum -a 256 "$tarball" | cut -d' ' -f1)"

# The package README states the highest minos of all bundled files.
min="$(tar -xJOf "$tarball" "$name/README.md" | sed -n 's/^Requires macOS \([0-9]*\).* or later\.$/\1/p')"
case "$min" in
    15) macos=sequoia ;;
    26) macos=tahoe ;;
    *) die "no Homebrew name for macOS '$min' (from $name/README.md); add it here" ;;
esac

cat <<EOF
# Generated by scripts/homebrew-formula.sh in $PROJECT_URL
class QemuGl < Formula
  desc "QEMU with OpenGL acceleration for guests (virtio-gpu-gl, Cocoa gl=on/gl=es)"
  homepage "$PROJECT_URL"
  url "$url"
  version "$version"
  sha256 "$sha256"
  license "GPL-2.0-only"

  livecheck do
    url :stable
    regex(/^v?(\d+(?:\.\d+)+-\d+)$/i)
    strategy :github_latest
  end

  depends_on arch: :arm64
  depends_on macos: :$macos

  conflicts_with "qemu", because: "both install the QEMU executables"

  # The package is self-contained, signed and notarized; its files reference
  # each other through @rpath. Keep those install names so that Homebrew
  # neither rewrites nor re-signs anything.
  preserve_rpath

  def install
    # QEMU finds lib/ and share/qemu relative to its resolved path, so the tree
    # stays together in libexec and only the executables are linked.
    libexec.install Dir["*"]
    bin.install_symlink libexec.glob("bin/*")
  end

  test do
    assert_match "QEMU emulator version #{version.to_s.split("-").first}",
                 shell_output("#{bin}/qemu-system-aarch64 --version")
    assert_match "virtio-gpu-gl-pci", shell_output("#{bin}/qemu-system-aarch64 -device help")
    system bin/"qemu-img", "create", "-f", "qcow2", testpath/"test.qcow2", "1M"
  end
end
EOF
